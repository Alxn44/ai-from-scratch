/** Idiomas con diccionario completo. De aquí salen los selectores. */
export const IDIOMAS = Object.keys(STR) as Lang[];
export const NOMBRE_IDIOMA: Record<string, string> = { es: 'ES', en: 'EN', fr: 'FR', pt: 'PT' };

export const t = (lang: string) => ((STR as unknown as Record<string, typeof STR.es>)[lang] ?? STR.es);

/** Idioma efectivo: la preferencia del usuario, o el del equipo cuando es 'auto'.
 *  Solo devuelve idiomas que tengan diccionario. */
export function resolveLang(pref: string, request: Request): Lang {
  if (IDIOMAS.includes(pref as Lang)) return pref as Lang;
  const accept = (request.headers.get('accept-language') ?? '').toLowerCase();
  for (const parte of accept.split(',')) {
    const cod = parte.trim().slice(0, 2) as Lang;
    if (cod !== 'es' && IDIOMAS.includes(cod)) return cod;
  }
  return 'es';
}
