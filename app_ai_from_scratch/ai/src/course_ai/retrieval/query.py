"""Query preparation and concept scoring. A pure function, top to bottom.

WHAT IS WRONG WITH COUNTING SUBSTRINGS, measured

Node's `buscar_en_curso` lowercases the query, strips accents, keeps the words
longer than two characters (at most six of them) and scores a lesson by how many
of those words occur as SUBSTRINGS of each of its text fields. Three consequences,
each one measured over the real corpus rather than reasoned about:

  1. `length > 2` is not a stopword rule. In Spanish it lets through
     `que como por con una modelo`, and in English `and model that the not you
     with`. They are the most frequent words in the language, so they hit almost
     every lesson and the ranking is decided by noise.
  2. SUBSTRING matching makes them worse than merely useless. `con` is inside
     *contexto*, *conversacion* and *consola*; `que` is inside *porque* and
     *aquel*. A stopword does not just add a point everywhere — it adds points in
     the places that look most like a real hit.
  3. Nothing bridges vocabulary. `aleatorio` occurs nowhere in twelve lessons, so
     «como lo hago menos aleatorio» scores zero and the model answers from memory.
     Worse, `random` occurs exactly once, in LESSON 2, so «how do i make it less
     random» routes confidently to the wrong lesson. That is not a miss to be
     out-scored; it is a poisoned route, and only an authored synonym fixes it.

WHAT THIS DOES INSTEAD

  · Whole WORDS, never substrings, after a light stem so `fotos`/`foto` and
    `puntajes`/`puntaje` are the same key.
  · An explicit stopword list per language, containing the measured survivors
    of the `length > 2` filter plus the rest of the question scaffolding
    (`how why what does`), all of which are exactly the words that match
    everything. A dropped word scores ZERO — it cannot out-rank anything,
    which is the property `test_retrieval.py` asserts by name for `por` and
    `que`.
  · A bilingual SYNONYM table from the beginner's word to a public glossary term.
    Every entry is drawn from the measured «absent from the corpus» list, which is
    the honest place for authored vocabulary: a word the corpus does not contain
    cannot be a copy of the corpus. This is the half no scoring change in Node can
    replace.
  · Three signals, each of them REPORTABLE, because the model has to be able to
    say where it found the answer: a glossary term matched, a synonym bridged, or
    a phrasing overlapped. `Ranked.reasons` carries all three and
    `entender_pregunta` hands them to the model as `por_que`.

The index is not consulted here and neither is the network: everything on this
page is a function of its arguments, so the routing half of the accuracy table in
test_retrieval.py runs with no database.

THE COLUMN IT IS COMPARED AGAINST DOES NEED NODE, and that is deliberate. It used
to be a dict typed by hand into ai/tests/queries.py, documented as «the measured
output of the real ranking over the real content» — and it disagreed with the real
scorer on 53 of 138 entries, so every «+N points» in this package was quoted
against a column no run produces. It is now generated by
scripts/emit-search-baseline.mjs, which calls `buscar_en_curso` itself. Slower,
and the only version of it that can be believed.
"""

