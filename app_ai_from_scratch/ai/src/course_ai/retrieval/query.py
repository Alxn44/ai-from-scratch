# HOW DISCRIMINATING A WORD IS, measured over the MAP and not over the corpus
#
# The first version of this scorer gave every shared word the same value and
# routed 49% of the 138 measured queries correctly — WORSE than the substring
# counter it is compared against (51%, generated by scripts/emit-search-baseline.mjs
# rather than transcribed). The reason was visible the moment it was written down:
# `sabe` occurs in the phrasings of lessons 1, 3 and 11, `guarda` in lesson 3
# alone, and treating them alike lets the vaguest word in the sentence pick the
# lesson. That is the same defect as Node's stopword problem, one level up — a word
# that is everywhere deciding the answer.
#
# So a word is worth log((N + 1) / df) where df is how many CONCEPTS use it. A word
# unique to one concept is worth log(13) = 2.56 and clears the floor on its own; a
# word shared by six is worth 0.77 and cannot route anything by itself.
#
# The `+ 1` is not cosmetic smoothing. Without it a word present in EVERY concept is
# worth exactly log(1) = 0, and a map with one concept in it has every word at zero
# and cannot route at all. With it a universal word is worth log(13/12) = 0.08:
# still unable to route anything by itself, which is the property that was wanted,
# and no longer a special case.
#
# The result is then divided by log(N + 1), so a word unique to one concept is worth
# 1.0 whatever the size of the map. That matters because FLOOR is an absolute
# number: un-normalised, the same question scores differently against a map of 12
# concepts and a map of 3, and the floor would quietly mean something different for
# each — a scorer whose verdict depends on the size of its input rather than on the
# question. The division is by a constant, so every ratio inside one map is
# untouched: measured, the 138-question table scores identically before and after.
#
# WHY THIS IS NOT THE THING THIS MODULE REFUSES TO DO. The counts are taken over
# the authored phrasings and the public glossary terms in `concepts.py` — data this
# repository wrote. It is not a document frequency over `lessons.technical`, which
# would be a statistic derived from the paid corpus and would carry its vocabulary
# back in through the numbers. Nothing here has ever read a lesson.
@dataclass(frozen=True, slots=True)
class Weights:
    """How discriminating each word of a map is, plus the value for one it has not
    seen. `unknown` travels WITH the table instead of being recomputed from the
    shipped map, so ranking against an injected fixture stays self-consistent."""

    idf: Mapping[str, float]      # 0 < value <= 1, one unique word = 1.0
    unknown: float

    def of(self, word: str) -> float:
        """An unseen word is worth as much as a unique one, never more.

        A stem the map has never seen cannot be matched at all, so this is not the
        common path — but a query word that matched through the six-character prefix
        rule can be absent from the table while its partner is present, and
        defaulting it to 0.0 would silently discard the very matches that rule
        exists to find.
        """
        return self.idf.get(word, self.unknown)


@lru_cache(maxsize=8)
def _weights(concepts: tuple[Concept, ...]) -> Weights:
    df: dict[str, int] = {}
    for c in concepts:
        seen: set[str] = set()
        for text in (*phrasings(c), *terms(c)):
            seen |= _stems(text)
        for w in seen:
            df[w] = df.get(w, 0) + 1
    n = len(concepts) + 1
    ceiling = math.log(n)
    return Weights(idf={w: math.log(n / k) / ceiling for w, k in df.items()},
                   unknown=1.0)


@dataclass(frozen=True, slots=True)
class Reason:
    """WHY this concept scored. `kind` is one of `termino`, `sinonimo`, `frase`."""

    kind: str
    detail: str
    points: float


@dataclass(frozen=True, slots=True)
class Ranked:
    concept: Concept
    score: float
    reasons: tuple[Reason, ...]

    @property
    def confidence(self) -> float:
        """0..1, for the model to read. A ratio against a fixed ceiling rather than
        against the runner-up: a normalisation against the second place reports 1.0
        for a single weak hit, which is the most confident-sounding thing this can
        say about the least evidence it can have."""
        return round(min(self.score / 12.0, 1.0), 2)


def _score(prepared: Prepared, c: Concept,
           idf: Weights) -> tuple[float, tuple[Reason, ...]]:
    reasons: list[Reason] = []
    total = 0.0

    # Both languages' terms, always. `lessons` and `labs` have no `lang` column, so
    # an English session is already searching a mostly-Spanish corpus in Node;
    # refusing to match an English question against a Spanish term here would throw
    # away the only routing signal that language has.
    # ONE QUERY WORD PAYS ONCE. Measured defect: the glossary carries several
    # surface forms of the same idea (`aprendizaje` and `aprender`; `peso` and
    # `pesos`), and `aprendio` matched both, so a single word in the question was
    # worth 2x W_TERM = 10 points. «donde guarda lo que aprendio» — a phrasing of
    # lesson 3, typed word for word — routed to lesson 1 on that doubling alone.
    # Tracking which query stems a term consumed keeps the genuinely independent
    # case intact: «hay una perilla para la creatividad» still scores `perilla
    # creativa` AND `creatividad`, because those are two different words in the
    # question rather than one word counted twice.
    hit_terms: list[str] = []
    consumed: set[str] = set()
    for t in terms(c):
        if t in hit_terms:
            continue
        matched = _term_stems(t, prepared.kept)
        if matched and not matched <= consumed:
            hit_terms.append(t)
            consumed |= matched
            total += W_TERM
            reasons.append(Reason("termino", t, W_TERM))

    for t in terms(c):
        if t in hit_terms:
            continue                      # already counted, and at the higher weight
        if any(_same(stem(b), stem(t)) or b == t for b in prepared.bridged):
            total += W_SYNONYM
            reasons.append(Reason("sinonimo", t, W_SYNONYM))
            hit_terms.append(t)

    # The best single phrasing, not the sum: a concept with twenty phrasings must
    # not out-score one with six by volume. What is summed inside one phrasing is
    # the DISCRIMINATING WEIGHT of the words shared with the query, so overlapping
    # on `guarda` (lesson 3 only) is worth three times overlapping on `sabe`
    # (lessons 1, 3 and 11).
    best = 0.0
    best_detail = ""
    for p in phrasings(c):
        target = _stems(p)
        if not target:
            continue
        # ONE QUERY WORD PAYS ONCE — ACROSS SIGNALS, not only inside the terms
        # loop above. `consumed` holds the query stems a term already paid for, and
        # a phrasing overlapping on the SAME query word is not new evidence: it is
        # one word of the question billed twice.
        #
        # Measured defect. «donde guarda lo que aprendio» is a phrasing of lesson 3
        # typed word for word, and it routed to lesson 1: there the single word
        # `aprendio` paid once as the term `aprendizaje` (5.0) and again as an
        # overlap on the phrasing «que es el aprendizaje automatico» (4.1) — 9.10
        # from ONE word, out-scoring lesson 3's 8.21 built from TWO, one of them
        # `guarda`, which no other concept in the map uses. Excluding the consumed
        # stems leaves lesson 1 at 5.0 and the verbatim phrasing wins.
        shared = [w for w in target
                  if any(_same(w, k) for k in prepared.kept if k not in consumed)]
        if not shared:
            continue
        value = W_PHRASE * sum(idf.of(w) for w in shared)
        if value > best:
            best = value
            best_detail = p
    if best > 0:
        total += best
        reasons.append(Reason("frase", best_detail, round(best, 2)))

    return total, tuple(reasons)


def rank(query: str, lang: Lang = "es", *,
         concepts: Sequence[Concept] = CONCEPTS,
         limit: int = 3) -> tuple[Ranked, ...]:
    """The concepts this question is about, best first, above the floor only.

    An empty result is a real answer and the important one: it means «say you do not
    know», not «pick the least bad lesson». `concepts` is injectable so a test can
    rank against a fixture map instead of the shipped one.
    """
    prepared = prepare(query, lang)
    idf = _weights(tuple(concepts))
    scored: list[Ranked] = []
    for c in concepts:
        total, reasons = _score(prepared, c, idf)
        if total >= FLOOR:
            scored.append(Ranked(c, round(total, 2), reasons))
    # The tie-break is the lesson number, so the same question always produces the
    # same answer. A tie broken by dict order changes with an edit somewhere else.
    scored.sort(key=lambda r: (-r.score, r.concept.leccion))
    return tuple(scored[:limit])


def rewrite(query: str, lang: Lang = "es", *, limit: int = 3) -> tuple[str, ...]:
    """The query strings to hand to the bridged `buscar_en_curso`, best first.

    The first is the discriminating words alone — which is already an improvement,
    because it is the original with the words that match everything taken out. The
    rest put the course's OWN vocabulary in front, since that is what the corpus
    actually contains: the beginner's `aleatorio` is not in twelve lessons and
    `temperatura` is in one.
    """
    prepared = prepare(query, lang)
    out: list[str] = []
    if prepared.surface:
        out.append(" ".join(prepared.surface))
    for r in rank(query, lang, limit=limit):
        for t in r.concept.terms_es[:1] + r.concept.terms_en[:1]:
            candidate = f"{t} {' '.join(prepared.surface[:3])}".strip()
            if candidate not in out:
                out.append(candidate)
    return tuple(out[:limit])
