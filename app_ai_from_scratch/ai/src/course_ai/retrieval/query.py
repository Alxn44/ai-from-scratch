# The shortest word that carries topic. Node used `length > 2` and that is kept,
# because the words it excludes in both languages are articles and prepositions —
# the disagreement is about the ones it LETS THROUGH, not about this bound.
MIN_WORD = 3

# What a signal is worth. The three are deliberately close: a glossary term is the
# strongest single piece of evidence, a bridged synonym is a term arrived at
# indirectly so it is worth slightly less, and a phrasing overlap is worth what its
# coverage says it is worth. Nothing here is worth zero and nothing dominates
# absolutely, so two weak signals can outvote one strong one — which is what makes
# «hay una perilla para la creatividad» land on temperature (perilla + creativa)
# rather than on parameters (perilla alone).
W_TERM = 5.0
W_SYNONYM = 4.0
W_PHRASE = 4.104

# Below this, `entender_pregunta` says `sin_ruta` instead of naming a lesson. The
# model is then told to say it does not know rather than answer from memory, which
# is the failure the whole module exists to prevent: a confident wrong lesson is
# worse than an admitted miss, because the student cannot tell.
#
# WHY IT IS W_TERM, and why it may not be a number picked by hand.
#
# The floor's job is to say what the LEAST evidence that may name a lesson is, and
# there is only one defensible answer: one glossary term of the course. «que es un
# token» is one term and has to route; anything weaker than one term must not.
#
# It used to be 3.0, which is BELOW W_PHRASE (4.104), and that inequality was the
# defect. One query word shared with one phrasing of one concept cleared the floor
# and routed, at confianza 0.34. Measured over the 182 pooled fixture questions
# (138 about a lesson, 44 about anything else): that bucket was 23 right and 24
# wrong — 49%, a coin flip — and it was 47 of the 115 answers the tool gave, so 41%
# of everything it said was decided by one ordinary word. «can it tell me the
# weather right now» routed to lesson 7 on `tell`; «it gave me a book title that
# does not exist» to lesson 8 on `book`;
# «cuanto cuesta el curso completo» to lesson 4 at confianza 1.0. In every case
# `por_que` named the phrasing, so the wrong route read as evidence-backed.
#
# WHAT IT COSTS, measured, because it is not free: the composed pipeline drops
# from 107 of 138 to 103, and the router alone from 85 to 61 — it declines 74
# instead of 41, and the gated `buscar_en_curso` covers most of those. What it buys
# is the whole confident-wrong population: over the 44 off-topic customer messages in
# `queries.OFF_TOPIC` the tool named a lesson for 18 of them at FLOOR = 3.0 and
# for 3 at FLOOR = W_TERM — and all 3 of those are caught before ranking by
# `intent.py`, so the shipped number is 0.
#
# The relation is asserted in test_retrieval.py rather than left as a comment:
# W_PHRASE < FLOOR <= W_TERM. A future edit to any of the three weights that
# re-opens the coin-flip bucket goes red on that inequality, which a hand-picked
# 4.5 could not do.
FLOOR = W_TERM


def strip_accents(text: str) -> str:
    """Same normalisation Node does (NFD, drop the combining marks), so a query
    typed with accents and one typed without are the same query on both sides."""
    return "".join(c for c in unicodedata.normalize("NFD", text)
                   if not unicodedata.combining(c))


def stopwords(lang: Lang) -> frozenset[str]:
    return STOPWORDS_EN if lang == "en" else STOPWORDS_ES


def synonyms(lang: Lang) -> Mapping[str, tuple[str, ...]]:
    return SYNONYMS_EN if lang == "en" else SYNONYMS_ES


def stem(word: str) -> str:
    """A deliberately tiny stemmer: plural only.

    It is not trying to be a morphological analyser. It exists so `fotos`/`foto`,
    `puntajes`/`puntaje` and `weights`/`weight` are one key, and it is applied to
    BOTH sides of every comparison, so even where it is wrong it is wrong
    consistently and cannot invent a match that the other side does not share.

    It strips a trailing «s» and nothing else. An earlier version also stripped
    «es», which is the correct Spanish plural rule and a trap in English: it turned
    `writes` into `writ` while `write` stayed `write`, so the two stopped matching
    each other and «it writes one word at a time» routed to lesson 1 on the word
    `writes` instead of to lesson 6 on the word `word`. Being wrong CONSISTENTLY is
    the whole value of a stemmer this small; being wrong in one direction only
    breaks the invariant it exists for.
    """
    if len(word) >= 4 and word.endswith("s"):
        return word[:-1]
    return word


def words(text: str) -> tuple[str, ...]:
    """Every alphanumeric run in the text, lowercased and unaccented. No filtering
    yet: `ampliar_consulta` has to be able to report what it DROPPED, which means
    the drop has to happen after this and not inside it."""
    flat = strip_accents(str(text).lower())
    out: list[str] = []
    token: list[str] = []
    for ch in flat:
        if ch.isalnum():
            token.append(ch)
        elif token:
            out.append("".join(token))
            token = []
    if token:
        out.append("".join(token))
    return tuple(out)


@dataclass(frozen=True, slots=True)
class Prepared:
    """A query, taken apart. `dropped` travels so the trace can show it."""

    original: str
    kept: tuple[str, ...]          # the discriminating words, stemmed
    surface: tuple[str, ...]       # the same words as typed, for the report
    dropped: tuple[str, ...]       # stopwords and too-short words, as typed
    bridged: tuple[str, ...]       # glossary terms reached through a synonym


def prepare(query: str, lang: Lang = "es") -> Prepared:
    """Normalise, drop the stopwords, expand into the course's own vocabulary.

    The synonym pass runs over the SURFACE words rather than the stems, because the
    table is authored as whole words and a stem like `confi` would quietly widen
    `confiar` into `configurar`.
    """
    stops = stopwords(lang)
    syn = synonyms(lang)
    kept: list[str] = []
    surface: list[str] = []
    dropped: list[str] = []
    bridged: list[str] = []
    for w in words(query):
        if len(w) < MIN_WORD or w in stops:
            dropped.append(w)
            continue
        surface.append(w)
        kept.append(stem(w))
        for target in syn.get(w, ()):
            if target not in bridged:
                bridged.append(target)
    return Prepared(original=str(query), kept=tuple(kept), surface=tuple(surface),
                    dropped=tuple(dropped), bridged=tuple(bridged))


def _stems(text: str) -> frozenset[str]:
    """The CONTENT stems of a phrasing: stopwords of BOTH languages removed.

    Measured defect this fixes. Coverage is `shared / len(target)`, and the target
    used to include the question scaffolding, so «donde guarda lo que aprendio» — a
    phrasing of lesson 3, matched word for word by a query typed exactly that way —
    scored 2/4 coverage because `donde` and `que` were dropped from the QUERY (they
    are stopwords) and kept in the PHRASING. Half its coverage was spent on words
    the query side is not even allowed to contribute. The union of both stopword
    lists is used because a phrasing is matched against questions in either
    language: that is the same reason `terms()` is read for both.
    """
    stops = STOPWORDS_ES | STOPWORDS_EN
    return frozenset(stem(w) for w in words(text)
                     if len(w) >= MIN_WORD and w not in stops)


def _same(a: str, b: str) -> bool:
    """Two stems name the same thing.

    Equality, or a common prefix of six characters or more. The prefix rule is what
    connects `aprende` to `aprendizaje` and `entrenar` to `entrenamiento` without a
    per-word exception list. Six is the measured floor at which it stops being
    noise: at five, `contar` matches `contexto`.
    """
    if a == b:
        return True
    if len(a) < 6 or len(b) < 6:
        return False
    n = 0
    for x, y in zip(a, b, strict=False):
        if x != y:
            break
        n += 1
    return n >= 6


def _term_matched(term: str, present: Iterable[str]) -> bool:
    """A term counts only when EVERY word of it is present.

    Multi-word terms are why: `perilla creativa` must not fire on `perilla` alone,
    or lesson 9 would win every question about parameters. Requiring all the words
    is also what lets `perilla` (lesson 3) and `perilla creativa` (lesson 9)
    coexist in one map without one swallowing the other.
    """
    return bool(_term_stems(term, present))


def _term_stems(term: str, present: Iterable[str]) -> frozenset[str]:
    """WHICH query stems a term matched, empty when it did not match at all.

    Same rule as `_term_matched` — every word of the term has to be present — but it
    reports what was consumed, so `_score` can refuse to pay twice for one word of
    the question. Returning the set rather than a bool is the whole difference
    between «this term matched» and «this term matched something new».
    """
    have = tuple(present)
    parts = [stem(w) for w in words(term) if len(w) >= MIN_WORD]
    if not parts:
        return frozenset()
    used: set[str] = set()
    for p in parts:
        hit = [h for h in have if _same(p, h)]
        if not hit:
            return frozenset()
        used.update(hit)
    return frozenset(used)


